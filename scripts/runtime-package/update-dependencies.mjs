#!/usr/bin/env node
/** Regenerate the reviewed library closure after an intentional lockfile update.
 * This edits metadata only: it never installs packages or executes client code.
 * Review the generated diff and run runtime-package tests before publishing.
 */
import * as fs from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../../', import.meta.url);
const lock = JSON.parse(fs.readFileSync(new URL('package-lock.json', root)));
if (lock.lockfileVersion !== 3) throw new Error('lockfile_v3_required');
const prod = Object.entries(lock.packages).filter(([name, value]) => name && !value.dev);
const entries = (optional) =>
  Object.fromEntries(
    prod
      .filter(([, value]) => Boolean(value.optional) === optional)
      .map(([name, value]) => [name.replace(/^node_modules\//, ''), value.version])
  );
const optional = entries(true);
// Deliberately narrow omission: only the SDK's own declared platform binaries.
const sdk = lock.packages['node_modules/@anthropic-ai/claude-agent-sdk'];
if (
  !sdk ||
  Object.entries(optional).some(
    ([name, version]) =>
      sdk.optionalDependencies?.[name] !== version ||
      !/^@anthropic-ai\/claude-agent-sdk-(linux|darwin|win32)-/.test(name)
  )
)
  throw new Error('review_new_optional_dependency_before_omission');
const hash = createHash('sha256').update(JSON.stringify(prod)).digest('hex');
fs.writeFileSync(
  new URL('scripts/runtime-package/dependencies.mjs', root),
  '// Generated by update-dependencies.mjs from the reviewed package-lock.json.\n' +
    '// Library integrity only, never a consumer harness-version admission gate.\n' +
    '// SDK optional platform clients are omitted because adapters use the user executable.\n' +
    `export const DEPENDENCIES = ${JSON.stringify(entries(false), null, 2)};\n` +
    `export const OMITTED_OPTIONAL_DEPENDENCIES = ${JSON.stringify(optional, null, 2)};\n` +
    `export const PRODUCTION_LOCK_SHA256 = ${JSON.stringify(hash)};\n`
);
// The TypeScript builds have distinct rootDir layouts. Emit the same reviewed
// metadata for both build targets, never a separately maintained support list.
fs.writeFileSync(
  new URL('src/core/runtime-dependencies.ts', root),
  '// Generated by scripts/runtime-package/update-dependencies.mjs from the reviewed lock.\n' +
    '// Same library metadata as scripts/runtime-package/dependencies.mjs; not a client gate.\n' +
    `export const DEPENDENCIES: Record<string, string> = ${JSON.stringify(entries(false), null, 2)};\n` +
    `export const PRODUCTION_LOCK_SHA256 = ${JSON.stringify(hash)};\n`
);
