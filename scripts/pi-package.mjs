#!/usr/bin/env node
/** Owner preview only by default. Apply always regenerates an exact A1 plan. */
import * as path from 'node:path';
import * as fs from 'node:fs';
import { digest } from './runtime-package/safety.mjs';
import { fileURLToPath } from 'node:url';
import {
  planActivation,
  applyActivation,
  planDeactivation,
  restoreActivation,
  observe,
} from './runtime-package/activation.mjs';
import { piSettingsStep, piPreferenceStep } from './runtime-package/pi.mjs';
export function piPackageCommand(args, env = process.env) {
  const [verb = 'preview', ...rest] = args;
  if (
    ![
      'preview',
      'apply',
      'row-7-preview',
      'row-7-apply',
      'row-10-preview',
      'row-10-apply',
      'restore-preview',
      'restore',
    ].includes(verb) ||
    rest.length % 2
  )
    throw Error('invalid_pi_activation_arguments');
  const o = {};
  for (let i = 0; i < rest.length; i += 2) {
    if (
      ![
        '--prefix',
        '--release',
        '--hud-home',
        '--shim-dir',
        '--node',
        '--settings',
        '--package',
        '--panel-auto-open',
        '--plan',
        '--receipt',
      ].includes(rest[i]) ||
      Object.hasOwn(o, rest[i])
    )
      throw Error('invalid_pi_activation_option');
    o[rest[i]] = rest[i + 1];
  }
  if (verb.startsWith('restore')) {
    if (!o['--receipt'] || (verb === 'restore' && !o['--plan']))
      throw Error('explicit_receipt_and_restore_plan_required');
    return verb === 'restore-preview'
      ? planDeactivation(o['--receipt'])
      : restoreActivation(o['--receipt'], o['--plan']);
  }
  if (!env.HOME || !o['--prefix'] || !o['--release']) throw Error('explicit_prefix_release_required');
  const options = {
    prefix: o['--prefix'],
    release: o['--release'],
    hudHome: o['--hud-home'] ?? env.HUD_HOME ?? path.join(env.HOME, '.hud'),
    shimDir: o['--shim-dir'] ?? path.join(env.HOME, '.local/bin'),
    path: env.PATH ?? '',
  };
  if (verb.startsWith('row-7')) {
    if (!o['--settings'] || !o['--package'] || o['--panel-auto-open'])
      throw Error('explicit_settings_and_package_required');
    const bindingFile = path.join(o['--package'], 'binding.json');
    const state = observe(bindingFile);
    if (state.kind !== 'file') throw Error('materialize_pi_package_first');
    const fd = fs.openSync(bindingFile, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
    let binding;
    try {
      const data = fs.readFileSync(fd);
      if (data.length > 16384 || digest(data) !== state.sha256) throw Error('pi_binding_changed');
      binding = JSON.parse(data);
    } finally {
      fs.closeSync(fd);
    }
    // Regenerate the trusted package pin read-only. Every generated byte must already
    // be receipt-backed and unchanged; row 7 itself still writes only declarative client steps.
    const materialized = planActivation({ ...options, pi: { node: binding.node } });
    if (materialized.piPackage !== o['--package'] || materialized.actions.some((s) => s.generated && !s.reused))
      throw Error('materialize_matching_pi_package_first');
    options.steps = [piSettingsStep(o['--settings'], o['--package'], observe)];
    const dirs = [];
    for (let p = path.dirname(o['--settings']); observe(p).kind === 'absent'; p = path.dirname(p))
      dirs.unshift({ kind: 'private-dir', path: p });
    options.steps.unshift(...dirs);
  } else if (verb.startsWith('row-10')) {
    if (!['true', 'false'].includes(o['--panel-auto-open']) || o['--settings'] || o['--package'])
      throw Error('explicit_panel_auto_open_required');
    options.steps = [piPreferenceStep(options.hudHome, o['--panel-auto-open'] === 'true', observe)];
  } else {
    if (!o['--node'] || o['--settings'] || o['--package'] || o['--panel-auto-open'])
      throw Error('explicit_node_required');
    options.pi = { node: o['--node'] };
  }
  if (verb.endsWith('apply') || verb === 'apply') {
    if (!o['--plan']) throw Error('explicit_plan_required');
    return applyActivation(options, o['--plan']);
  }
  if (o['--plan']) throw Error('preview_has_no_plan_argument');
  return planActivation(options);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv[2] === '--help')
      console.log(
        'node RELEASE/pi-package.mjs preview|apply --prefix ABS --release DIGEST --node ABS [--hud-home ABS --shim-dir ABS] [--plan ID]\nrow-7-preview|row-7-apply --prefix ABS --release DIGEST --settings ABS --package MATERIALIZED_ABS [--plan ID]\nrow-10-preview|row-10-apply --prefix ABS --release DIGEST --panel-auto-open true|false [--plan ID]\nrestore-preview|restore --receipt ABS [--plan ID]\nRows 7 and 10 are separate owner confirmations; never writes mcp.json, never reloads a client.'
      );
    else console.log(JSON.stringify(piPackageCommand(process.argv.slice(2)), null, 2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
