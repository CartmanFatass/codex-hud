/** Ticket briefs and the one-way GitHub Issues mirror. */
import { execFile } from 'node:child_process';
import { writeFileAtomic as replaceFile } from '../utils/atomic-fs.js';
import * as fs from 'node:fs';
import { join } from 'node:path';
import { scanTicketStore } from '../collectors/ticket-store.js';
import { TICKET_FEATURE, parseTicketRef, renderTicketBrief } from '../tickets/format.js';
import type { HudIO } from './hud.js';
import { CliError } from './private-home.js';

const USAGE = 'usage: hud tickets sync [--cwd DIR]';
const SHOW_USAGE = 'usage: hud tickets show <feature>[/<NN>]';
const MARKER_PREFIX = '<!-- Generated by hud tickets sync from ';
const TRIAGE_LABELS = ['needs-triage', 'needs-info', 'ready-for-agent', 'ready-for-human'] as const;
const MAX_SLUG = 48;
const MAX_COMMENTS = 5;
const MAX_BODY_BYTES = 56 * 1024;
const MAX_COMMENT_CHARS = 240;

export interface GhResult { stdout: string; stderr: string; code: number | null; errorCode?: string; }
export type GhRunner = (args: readonly string[], cwd: string, env: NodeJS.ProcessEnv) => Promise<GhResult>;

interface GhIssue {
  number: number; title: string; body?: string | null; state: string; state_reason?: string | null;
  html_url?: string; assignee?: unknown; assignees?: unknown[]; labels?: ({ name?: string } | string)[];
  comments?: number; pull_request?: unknown; sub_issues_summary?: { total?: number };
}
interface GhComment { user?: { login?: string | null } | null; created_at?: string; body?: string | null; }
interface WriteFilePlan { path: string; content: string; kind: 'md' | 'gitignore'; }
interface FeaturePlan { slug: string; ticketCount: number; dir: string; files: WriteFilePlan[]; deletes: string[]; }

async function showTickets(args: readonly string[], io: HudIO): Promise<number> {
  if (args.length === 1 && args[0] === '--help') { await io.stdout(`${SHOW_USAGE}\n`); return 0; }
  if (args.length !== 1) throw new CliError(SHOW_USAGE);
  const id = parseTicketRef(args[0]), feature = id?.feature ?? args[0];
  if (!TICKET_FEATURE.test(feature)) throw new CliError(SHOW_USAGE);
  const source = scanTicketStore(process.cwd()).sources.get(feature);
  if (!source) throw new CliError(`ticket feature not found or unreadable: ${feature}`, 1);
  const entries = 'doc' in source ? source.doc.tickets : source.legacy;
  const selected = id ? entries.filter(({ number }) => number === id.number) : entries;
  if (id && selected.length !== 1) throw new CliError(`ticket not found or ambiguous: ${args[0]}`, 1);
  const title = 'doc' in source ? source.doc.title ?? feature : feature;
  const briefs = selected.map((ticket) => ('brief' in ticket ? ticket.brief : renderTicketBrief(ticket, 'doc' in source ? source.doc : {})).trimEnd());
  await io.stdout([...(id ? [] : [`# ${title}`]), ...briefs].join('\n\n') + '\n');
  return 0;
}

export async function ticketsCommand(args: readonly string[], io: HudIO, runGh: GhRunner = execGh): Promise<number> {
  if (args.length === 1 && args[0] === '--help') { await io.stdout(`${USAGE}\n${SHOW_USAGE}\n`); return 0; }
  if (args[0] === 'show') return showTickets(args.slice(1), io);
  if (args[0] !== 'sync') throw new CliError(`${USAGE}\n${SHOW_USAGE}`);
  const rest = args.slice(1);
  if (rest.length === 1 && rest[0] === '--help') { await io.stdout(`${USAGE}\n`); return 0; }
  const cwd = parseSyncArgs(rest), scratchDir = join(cwd, '.scratch');
  const existingSpecs = scanScratch(scratchDir);

  const gh = createGhClient(runGh, cwd, io.env);
  const repoView = await gh.json<{ nameWithOwner?: string }>(['repo', 'view', '--json', 'nameWithOwner']);
  const repo = repoView?.nameWithOwner?.trim();
  if (!repo || !/^[^/\s]+\/[^/\s]+$/.test(repo)) throw new CliError('could not resolve GitHub owner/repo from git remote', 1);

  const existingByIssue = existingForRepo(existingSpecs, repo);
  const openRaw = await gh.list<GhIssue>(`repos/${repo}/issues?state=open&per_page=100`);
  const issuesByNumber = new Map<number, GhIssue>();
  const openIssues = openRaw.filter((item) => !item?.pull_request && typeof item?.number === 'number');
  for (const issue of openIssues) issuesByNumber.set(issue.number, issue);

  const parents: { parent: GhIssue; subs: GhIssue[]; preferredSlug?: string }[] = [];
  const seenParents = new Set<number>();
  for (const issue of openIssues) {
    if (issue.sub_issues_summary?.total === 0 && !existingByIssue.has(issue.number)) continue;
    const subs = await gh.list<GhIssue>(`repos/${repo}/issues/${issue.number}/sub_issues?per_page=100`);
    for (const sub of subs) issuesByNumber.set(sub.number, sub);
    if (subs.length > 0 || existingByIssue.has(issue.number)) {
      seenParents.add(issue.number);
      parents.push({ parent: issue, subs, preferredSlug: existingByIssue.get(issue.number) });
    }
  }
  for (const [issueNum, existingSlug] of existingByIssue) {
    if (seenParents.has(issueNum)) continue;
    const parent = await gh.json<GhIssue>(['api', `repos/${repo}/issues/${issueNum}`]);
    issuesByNumber.set(parent.number, parent);
    const subs = await gh.list<GhIssue>(`repos/${repo}/issues/${issueNum}/sub_issues?per_page=100`);
    for (const sub of subs) issuesByNumber.set(sub.number, sub);
    parents.push({ parent, subs, preferredSlug: existingSlug });
  }

  const featurePlans = await buildPlans(parents, repo, scratchDir, issuesByNumber, gh, new Set(existingSpecs.keys()));
  validateWriteSafety(featurePlans);
  applyPlans(featurePlans);

  let totalTickets = 0;
  for (const feature of featurePlans) {
    totalTickets += feature.ticketCount;
    await io.stdout(`${feature.slug}: ${feature.ticketCount} tickets\n`);
  }
  await io.stdout(`synced ${featurePlans.length} features, ${totalTickets} tickets\n`);
  return 0;
}

function parseSyncArgs(args: readonly string[]): string {
  let cwdArg: string | undefined;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--cwd') {
      const dir = args[++i];
      if (cwdArg || !dir || dir.startsWith('-')) throw new CliError(USAGE);
      cwdArg = dir;
    } else throw new CliError(USAGE);
  }
  if (!cwdArg) return process.cwd();
  try {
    const resolved = fs.realpathSync(cwdArg);
    if (fs.statSync(resolved).isDirectory()) return resolved;
  } catch { /* fall through */ }
  throw new CliError(`not a directory: ${cwdArg}`);
}

function execGh(args: readonly string[], cwd: string, env: NodeJS.ProcessEnv): Promise<GhResult> {
  return new Promise((resolve) => {
    execFile('gh', [...args], { cwd, env, encoding: 'utf8', maxBuffer: 10 * 1024 * 1024 }, (err, stdout, stderr) => {
      if (!err) { resolve({ stdout, stderr, code: 0 }); return; }
      const nodeErr = err as NodeJS.ErrnoException & { code?: number | string };
      resolve({
        stdout: stdout ?? '', stderr: stderr ?? '',
        code: typeof nodeErr.code === 'number' ? nodeErr.code : 1,
        errorCode: typeof nodeErr.code === 'string' ? nodeErr.code : undefined,
      });
    });
  });
}

function createGhClient(runGh: GhRunner, cwd: string, env: NodeJS.ProcessEnv) {
  const run = async (args: readonly string[]): Promise<GhResult> => {
    const res = await runGh(args, cwd, env);
    if (res.errorCode === 'ENOENT') throw new CliError('gh is missing from PATH', 1);
    return res;
  };
  const fail = (res: GhResult, context: string): never => {
    const line = res.stderr.split(/\r?\n/).map((l) => l.trim()).find(Boolean);
    throw new CliError(line ? `gh failed (${context}): ${line}` : `gh failed (${context})`, 1);
  };
  const parseJson = <T>(raw: string, context: string): T => {
    try { return JSON.parse(raw) as T; }
    catch { throw new CliError(`invalid JSON from gh (${context})`, 1); }
  };
  const parseList = <T>(raw: string, endpoint: string): T[] => {
    const parsed = parseJson<unknown>(raw, endpoint);
    if (!Array.isArray(parsed)) throw new CliError(`expected JSON array from gh (${endpoint})`, 1);
    return (Array.isArray(parsed[0]) ? parsed.flat() : parsed) as T[];
  };
  return {
    async json<T>(args: readonly string[]): Promise<T> {
      const res = await run(args);
      if (res.code !== 0) fail(res, args.join(' '));
      return parseJson<T>(res.stdout, args.join(' '));
    },
    async list<T>(endpoint: string): Promise<T[]> {
      const res = await run(['api', '--paginate', '--slurp', endpoint]);
      if (res.code !== 0) fail(res, endpoint);
      return parseList<T>(res.stdout, endpoint);
    },
    async tryList<T>(endpoint: string): Promise<T[] | null> {
      const res = await run(['api', '--paginate', '--slurp', endpoint]);
      if (res.code !== 0) {
        if (/\b(404|410|501)\b|Not Found/i.test(res.stderr)) return null;
        fail(res, endpoint);
      }
      return parseList<T>(res.stdout, endpoint);
    },
  };
}

function isGeneratedContent(text: string): boolean {
  const firstLine = text.split(/\r?\n/, 1)[0] ?? '';
  return firstLine.startsWith(MARKER_PREFIX) && firstLine.endsWith('-->');
}

function readMarkerIfFile(path: string): { exists: boolean; symlink: boolean; firstLine: string } {
  try {
    const st = fs.lstatSync(path);
    if (st.isSymbolicLink() || !st.isFile()) return { exists: true, symlink: true, firstLine: '' };
    const buf = Buffer.alloc(512), fd = fs.openSync(path, 'r');
    try {
      const bytes = fs.readSync(fd, buf, 0, buf.length, 0);
      return { exists: true, symlink: false, firstLine: buf.subarray(0, bytes).toString('utf8').split(/\r?\n/, 1)[0] ?? '' };
    } finally { fs.closeSync(fd); }
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return { exists: false, symlink: false, firstLine: '' };
    throw err;
  }
}

/** Return the mirror's spec markers; refuse files belonging to the other kind of tracker. */
export function scanScratch(scratchDir: string, local = false): Map<string, string> {
  const refuseMirror = () => {
    throw new CliError('refusing local ticket edits: .scratch is a GitHub mirror; edit issues with gh, then call hud_tickets with op: sync', 1);
  };
  const specs = new Map<string, string>();
  let entries: fs.Dirent[];
  try {
    const st = fs.lstatSync(scratchDir);
    if (!st.isDirectory()) throw new CliError(`${local ? 'refusing local ticket edits' : 'refusing to sync'}: .scratch is not a directory`, 1);
    entries = fs.readdirSync(scratchDir, { withFileTypes: true });
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return specs;
    if (err instanceof CliError) throw err;
    throw new CliError('cannot read .scratch directory', 1);
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const slug = entry.name, issuesDir = join(scratchDir, slug, 'issues');
    try {
      if (fs.lstatSync(issuesDir).isDirectory()) {
        for (const name of fs.readdirSync(issuesDir)) {
          if (!name.endsWith('.md')) continue;
          const info = readMarkerIfFile(join(issuesDir, name));
          const generated = !info.symlink && isGeneratedContent(info.firstLine);
          if (local && generated) refuseMirror();
          if (!local && !generated) {
            throw new CliError(`refusing to sync: non-generated ticket file at .scratch/${slug}/issues/${name}`, 1);
          }
        }
      }
    } catch (err) {
      if (err instanceof CliError) throw err;
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
    }
    const specInfo = readMarkerIfFile(join(scratchDir, slug, 'spec.md'));
    if (specInfo.exists && !specInfo.symlink && isGeneratedContent(specInfo.firstLine)) {
      if (local) refuseMirror();
      specs.set(slug, specInfo.firstLine);
    }
  }
  return specs;
}

function existingForRepo(specs: Map<string, string>, repo: string): Map<number, string> {
  const out = new Map<number, string>();
  for (const [slug, line] of specs) {
    const match = line.match(/^<!-- Generated by hud tickets sync from https?:\/\/[^/]+\/([^/]+\/[^/]+)\/issues\/(\d+) -->$/);
    if (!match || match[1].toLowerCase() !== repo.toLowerCase()) continue;
    const num = Number(match[2]);
    if (Number.isInteger(num) && num > 0 && !out.has(num)) out.set(num, slug);
  }
  return out;
}

async function buildPlans(
  parents: { parent: GhIssue; subs: GhIssue[]; preferredSlug?: string }[],
  repo: string, scratchDir: string, issuesByNumber: Map<number, GhIssue>, gh: ReturnType<typeof createGhClient>,
  reservedSlugs: ReadonlySet<string> = new Set()
): Promise<FeaturePlan[]> {
  const usedSlugs = new Set<string>(reservedSlugs), assignedSlugs = new Set<string>(), plans: FeaturePlan[] = [];
  for (const { parent, subs, preferredSlug } of parents) {
    let slug: string;
    if (preferredSlug) {
      if (assignedSlugs.has(preferredSlug)) throw new Error(`duplicate mirror directory plan: ${preferredSlug}`);
      slug = preferredSlug;
    } else {
      const base = slugify(parent.title, parent.number);
      slug = base;
      if (usedSlugs.has(slug)) {
        slug = withSlugSuffix(base, `-${parent.number}`);
        while (usedSlugs.has(slug)) {
          const next = withSlugSuffix(slug, `-${parent.number}`);
          if (next.length <= slug.length) {
            for (let n = 2; usedSlugs.has(slug); n++) slug = withSlugSuffix(base, `-${parent.number}-${n}`);
            break;
          }
          slug = next;
        }
      }
    }
    usedSlugs.add(slug);
    assignedSlugs.add(slug);
    const featureDir = join(scratchDir, slug), issuesDir = join(featureDir, 'issues');
    const files: WriteFilePlan[] = [
      { path: join(featureDir, '.gitignore'), content: '*\n', kind: 'gitignore' },
      { path: join(featureDir, 'spec.md'), content: renderSpec(parent, repo), kind: 'md' },
    ];
    const desiredNames = new Set<string>();
    for (const sub of subs) {
      const blockers = await resolveOpenBlockers(sub, repo, issuesByNumber, gh);
      const comments = sub.comments === 0 ? [] : (await gh.list<GhComment>(`repos/${repo}/issues/${sub.number}/comments?per_page=100`)).slice(-MAX_COMMENTS);
      const fileName = `${sub.number}-${slugify(sub.title, sub.number)}.md`;
      desiredNames.add(fileName);
      files.push({ path: join(issuesDir, fileName), content: renderTicket(sub, repo, blockers, comments), kind: 'md' });
    }
    const deletes: string[] = [];
    try {
      if (fs.lstatSync(issuesDir).isDirectory()) {
        for (const name of fs.readdirSync(issuesDir)) if (name.endsWith('.md') && !desiredNames.has(name)) deletes.push(join(issuesDir, name));
      }
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
    }
    plans.push({ slug, ticketCount: subs.length, dir: issuesDir, files, deletes });
  }
  return plans;
}

async function resolveOpenBlockers(
  issue: GhIssue, repo: string, issuesByNumber: Map<number, GhIssue>, gh: ReturnType<typeof createGhClient>
): Promise<number[]> {
  const nativeDeps = await gh.tryList<GhIssue>(`repos/${repo}/issues/${issue.number}/dependencies/blocked_by?per_page=100`);
  if (nativeDeps && nativeDeps.length > 0) {
    return [...new Set(nativeDeps.filter((d) => d.state === 'open' && typeof d.number === 'number').map((d) => d.number))].sort((a, b) => a - b);
  }
  const bodyRefs = parseBodyBlockers(issue.body);
  if (bodyRefs.length === 0) return [];
  const open: number[] = [];
  for (const num of bodyRefs) {
    let target = issuesByNumber.get(num);
    if (!target) {
      target = await gh.json<GhIssue>(['api', `repos/${repo}/issues/${num}`]);
      issuesByNumber.set(num, target);
    }
    if (target.state === 'open') open.push(num);
  }
  return [...new Set(open)].sort((a, b) => a - b);
}

function parseBodyBlockers(body: string | null | undefined): number[] {
  if (!body) return [];
  const line = body.match(/^[ \t]*(?:\*\*)?Blocked by:(?:\*\*)?[ \t]*([^\r\n]*)/im)?.[1]?.trim();
  if (!line || /^none\b/i.test(line)) return [];
  const nums: number[] = [];
  for (const match of line.matchAll(/#?(\d+)\b/g)) {
    const n = Number(match[1]);
    if (Number.isInteger(n) && n > 0) nums.push(n);
  }
  return nums;
}

function validateWriteSafety(plans: FeaturePlan[]): void {
  const seenDirs = new Set<string>();
  for (const plan of plans) {
    if (seenDirs.has(plan.dir)) throw new Error(`duplicate mirror directory plan: ${plan.dir}`);
    seenDirs.add(plan.dir);
    for (const file of plan.files) {
      if (file.kind === 'gitignore') {
        try {
          const st = fs.lstatSync(file.path);
          if (st.isSymbolicLink() || !st.isFile()) throw new CliError(`refusing to overwrite non-regular file: ${file.path}`, 1);
          const cur = fs.readFileSync(file.path, 'utf8').trim();
          if (cur !== '' && cur !== '*') throw new CliError(`refusing to overwrite non-generated .gitignore: ${file.path}`, 1);
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
        }
        continue;
      }
      const info = readMarkerIfFile(file.path);
      if (info.exists && (info.symlink || !isGeneratedContent(info.firstLine))) {
        throw new CliError(`refusing to overwrite non-generated file: ${file.path}`, 1);
      }
    }
    for (const delPath of plan.deletes) {
      const info = readMarkerIfFile(delPath);
      if (!info.exists || info.symlink || !isGeneratedContent(info.firstLine)) {
        throw new CliError(`refusing to delete non-generated file: ${delPath}`, 1);
      }
    }
  }
}

export function writeFileAtomic(filePath: string, content: string, mode?: number): void {
  replaceFile(filePath, content, { mkdir: false, dotPrefix: true, mode: (mode ?? 0o666) & ~process.umask() });
}

function applyPlans(plans: FeaturePlan[]): void {
  for (const plan of plans) {
    fs.mkdirSync(plan.dir, { recursive: true });
    for (const file of plan.files) writeFileAtomic(file.path, file.content);
    for (const delPath of plan.deletes) fs.unlinkSync(delPath);
  }
}

function withSlugSuffix(slug: string, suffix: string): string {
  return `${slug.slice(0, Math.max(1, MAX_SLUG - suffix.length)).replace(/-+$/, '')}${suffix}`;
}

export function slugify(title: string, issueNumber: number): string {
  const ascii = title.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return ascii.slice(0, MAX_SLUG).replace(/-+$/, '') || `issue-${issueNumber}`;
}

const cleanLine = (text: string) => text.replace(/\s+/g, ' ').trim();
const normalizeBody = (body: string | null | undefined) => (body ?? '').replace(/\r\n/g, '\n').trim();

function truncateBody(body: string, maxBytes: number): string {
  if (!body || Buffer.byteLength(body, 'utf8') <= maxBytes) return body;
  const sliced = Buffer.from(body, 'utf8').subarray(0, maxBytes).toString('utf8');
  return `${sliced.replace(/\uFFFD+$/, '').trimEnd()}\n… (truncated)`;
}

function deriveStatus(issue: GhIssue): string {
  if (issue.state === 'closed') return issue.state_reason === 'not_planned' ? 'wontfix' : 'resolved';
  if (issue.assignee || (Array.isArray(issue.assignees) && issue.assignees.length > 0)) return 'claimed';
  const labels = new Set((issue.labels ?? []).map((l) => (typeof l === 'string' ? l : l?.name ?? '').toLowerCase()));
  return TRIAGE_LABELS.find((label) => labels.has(label)) ?? 'needs-triage';
}

const issueUrl = (issue: GhIssue, repo: string) => issue.html_url || `https://github.com/${repo}/issues/${issue.number}`;

function renderSpec(parent: GhIssue, repo: string): string {
  const url = issueUrl(parent, repo), title = cleanLine(parent.title) || `Issue ${parent.number}`, body = normalizeBody(parent.body);
  const parts = [`${MARKER_PREFIX}${url} -->`, `# ${title}`, '', `Source: ${url}`];
  if (body) parts.push('', body);
  return parts.join('\n') + '\n';
}

function renderTicket(issue: GhIssue, repo: string, blockers: number[], comments: GhComment[]): string {
  const url = issueUrl(issue, repo), title = cleanLine(issue.title) || `Issue ${issue.number}`;
  const status = deriveStatus(issue), blocked = blockers.length ? blockers.join(', ') : 'none';
  const body = truncateBody(normalizeBody(issue.body), MAX_BODY_BYTES);
  const parts = [`${MARKER_PREFIX}${url} -->`, `# ${issue.number}: ${title}`, '', `**Status:** ${status}`, `**Blocked by:** ${blocked}`];
  if (body) parts.push('', body);
  if (comments.length > 0) {
    const bullets = comments.map((c) => {
      const author = c.user?.login?.trim() || 'unknown';
      const date = c.created_at ? c.created_at.slice(0, 10) : 'unknown-date';
      const firstLine = (c.body ?? '').split(/\r?\n/).map((l) => cleanLine(l)).find(Boolean) ?? '';
      const snippet = firstLine.length > MAX_COMMENT_CHARS ? `${firstLine.slice(0, MAX_COMMENT_CHARS - 1)}…` : firstLine;
      return `- ${date} ${author}${snippet ? `: ${snippet}` : ''}`;
    });
    parts.push('', '## Comments', '', ...bullets);
  }
  return parts.join('\n') + '\n';
}
