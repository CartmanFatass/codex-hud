const SYNC_USAGE = 'usage: hud tickets sync [--cwd DIR]';
const COMMIT_USAGE = 'usage: hud tickets commit [--cwd DIR]';
const SHOW_USAGE = 'usage: hud tickets show <feature>[/<NN>]';
const MIGRATE_USAGE = 'usage: hud tickets migrate [--cwd DIR] [--delete-legacy]';
const USAGE = `${SYNC_USAGE}\n${COMMIT_USAGE}\n${SHOW_USAGE}\n${MIGRATE_USAGE}`;
