const EN_OVERRIDES: Record<string, string> = {
  // Setting values whose stored form is not a word in either language.
  en: 'English',
  zh: '中文',
  'dock: push': 'push',
  // Schedule names the unit in its heading; Chinese uses a classifier on the fold row.
  '{n} more items': '{n} more',
  // Chinese words a batch's unstarted items apart from requests that wait for the owner.
  'batch: {n} waiting': '{n} waiting',
};

export function t(text: string, vars?: Record<string, string | number>): string {
  const template = current === 'zh' ? (ZH[text] ?? text) : (EN_OVERRIDES[text] ?? text);
  return vars
    ? template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
    : template;
}
